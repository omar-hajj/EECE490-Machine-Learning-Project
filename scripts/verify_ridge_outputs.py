"""Independently replay saved models and reconcile their validation reports.

Does not import project feature, training, or scoring functions. Only loads
model files generated by this project's own training run, after hash checks.
"""

import argparse
from collections import defaultdict
from datetime import datetime, timedelta
import csv
import hashlib
import json
import math
from pathlib import Path


def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha256(path):
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def independent_features(series, timestamp, lags, weather=None):
    values = {"hour_of_week": str(timestamp.weekday() * 24 + timestamp.hour)}
    latest = None
    for lag in lags:
        source_hour = timestamp - timedelta(hours=lag)
        available_at = source_hour + timedelta(hours=1)
        require(available_at <= timestamp.replace(hour=0), "Input would arrive after midnight")
        if source_hour not in series:
            return None, None
        values[f"lag_{lag}h"] = series[source_hour]
        latest = max(latest or available_at, available_at)
    if weather is not None:
        entry = weather.get(timestamp)
        if entry is None:
            return None, None
        require(entry["available_at"] <= timestamp.replace(hour=0), "Nominal weather arrives after midnight")
        values.update(entry["features"])
        latest = max(latest, entry["available_at"])
    return values, latest


def measured(actual, predictions):
    n = len(actual)
    errors = [abs(float(predicted) - observed) for observed, predicted in zip(actual, predictions)]
    mean_actual = math.fsum(actual) / n
    mae = math.fsum(errors) / n
    return {"observations": n, "mae": mae,
            "rmse": math.sqrt(math.fsum(error * error for error in errors) / n),
            "maximum_absolute_error": max(errors), "mean_actual": mean_actual,
            "nmae": mae / mean_actual if mean_actual else None}


def compare_scores(expected, observed):
    for key, value in expected.items():
        other = observed[key]
        if value is None:
            require(other is None, f"Expected undefined {key}")
        else:
            require(math.isclose(value, other, rel_tol=1e-10, abs_tol=1e-10), f"Score differs: {key}")


def main():
    import joblib
    import numpy as np
    from threadpoolctl import threadpool_limits

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--baseline-dir", required=True, type=Path)
    parser.add_argument("--ridge-dir", "--model-dir", dest="ridge_dir", required=True, type=Path)
    parser.add_argument("--archive", required=True, type=Path)
    parser.add_argument("--weather-features", type=Path)
    args = parser.parse_args()
    report = json.loads((args.ridge_dir / "results.json").read_text())
    boosting = report.get("model") == "XGBoost"
    prefix = "xgboost" if boosting else "ridge"
    require(not report["test_period_scored"], "Reserved test must not be scored")
    require(sha256(args.archive) == report["source_sha256"], "Source archive differs")
    for name, digest in report["input_sha256"].items():
        require(sha256(args.baseline_dir / name) == digest, "Model input changed: " + name)
    groups = {(group["site_id"], group["target"]): group for group in report["groups"]}
    weather = None
    if report["weather_used"]:
        require(args.weather_features is not None, "Aligned weather path is required")
        require(report["configuration"]["weather"]["provisional_nominal_availability_approved_by_user"], "Unapproved weather assumption")
        for name, digest in report["weather_input_sha256"].items():
            require(sha256(args.weather_features.with_name(name)) == digest, "Weather input changed")
        metadata = report["weather_alignment_metadata"]
        weather = defaultdict(dict)
        with args.weather_features.open(encoding="utf-8", newline="") as stream:
            for row in csv.DictReader(stream):
                weather[row["site_id"]][datetime.fromisoformat(row["timestamp_local"])] = {
                    "features": {name: float(row[name]) for name in metadata["feature_names"]},
                    "available_at": datetime.fromisoformat(row["nominal_available_at_local"])}
    series = defaultdict(dict)
    with (args.baseline_dir / "hourly_data.csv").open(encoding="utf-8", newline="") as stream:
        for row in csv.DictReader(stream):
            key = row["site_id"], row["target"]
            if key not in groups:
                continue
            timestamp = datetime.fromisoformat(row["timestamp_local_unverified"])
            require(timestamp < datetime.fromisoformat(groups[key]["validation_end_exclusive"]), "Test target in prepared inputs")
            series[key][timestamp] = float(row["value_source_units"])
    baselines = defaultdict(lambda: defaultdict(dict))
    with (args.baseline_dir / "validation_predictions.csv").open(encoding="utf-8", newline="") as stream:
        for row in csv.DictReader(stream):
            key = row["site_id"], row["target"]
            timestamp = datetime.fromisoformat(row["timestamp_local_unverified"])
            baselines[key][timestamp][row["method"]] = float(row["prediction"]) if row["prediction"] else None
    saved = defaultdict(dict)
    with (args.ridge_dir / "validation_predictions.csv").open(encoding="utf-8", newline="") as stream:
        for row in csv.DictReader(stream):
            key = row["site_id"], row["target"]
            timestamp = datetime.fromisoformat(row["timestamp_local_unverified"])
            require(timestamp not in saved[key], "Repeated model prediction")
            saved[key][timestamp] = row
    count = 0
    with threadpool_limits(limits=1):
        for key, group in groups.items():
            if group["status"] != "validation_tuned_not_final_tested":
                continue
            start, end = (datetime.fromisoformat(group[name]) for name in ("validation_start", "validation_end_exclusive"))
            site_weather = weather[key[0]] if weather is not None else None
            training = []
            for timestamp, actual in sorted(series[key].items()):
                if timestamp < start:
                    features, _ = independent_features(series[key], timestamp, report["configuration"]["lag_hours"], site_weather)
                    if features is not None:
                        training.append(features)
            require(len(training) == group["training_rows"], "Training count differs")
            require(datetime.fromisoformat(group["training_last_target"]) < start, "Validation target used for training")
            model_path = (args.ridge_dir / group["model_file"]).resolve()
            require(model_path.is_relative_to(args.ridge_dir.resolve()), "Model path escapes run directory")
            require(sha256(model_path) == group["model_sha256"], "Saved model changed")
            model = joblib.load(model_path)
            vectorizer = model.named_steps["vectorizer"]
            transformed_training = vectorizer.transform(training)
            expected_names = {f"{name}={value}" if isinstance(value, str) else name for row in training for name, value in row.items()}
            require(set(vectorizer.get_feature_names_out()) == expected_names, "Feature vocabulary contains non-training features")
            if not boosting:
                scaler = model.named_steps["scaler"]
                require(np.allclose(transformed_training.mean(axis=0), scaler.mean_, rtol=1e-10, atol=1e-10), "Scaler mean contains other data")
                require(int(scaler.n_samples_seen_) == len(training), "Scaler fitted on a different number of rows")
                require(float(model.named_steps["ridge"].alpha) == group["selected_alpha"], "Saved alpha differs")
            else:
                for parameter, value in group["selected_parameters"].items():
                    require(model.named_steps["boosting"].get_params()[parameter] == value, "Saved XGBoost parameter differs")
            search = group["parameter_search" if boosting else "alpha_search"]
            minimum_error = min(item["common_validation_scores_raw"]["mae"] for item in search)
            require(math.isclose(minimum_error, group[f"{prefix}_common_scores_raw"]["mae"], rel_tol=1e-12), "Candidate selection differs")
            common_actual, common_predicted = [], []
            common_baselines = defaultdict(list)
            own_actual, own_predicted = [], []
            require(len(saved[key]) == int((end - start).total_seconds() / 3600), "Missing calendar rows")
            for timestamp, row in sorted(saved[key].items()):
                require(start <= timestamp < end, "Prediction outside validation")
                require(datetime.fromisoformat(row["issue_time_local_unverified"]) == timestamp.replace(hour=0), "Wrong issue time")
                actual = float(row["actual"]) if row["actual"] else None
                require(actual == series[key].get(timestamp), "Wrong observed value")
                features, available_at = independent_features(series[key], timestamp, report["configuration"]["lag_hours"], site_weather)
                predicted = float(row["prediction_raw"]) if row["prediction_raw"] else None
                if features is None:
                    require(predicted is None, "Prediction exists with absent lag inputs")
                else:
                    # Replay exported scaler and coefficients directly, and
                    # check the public model API gives the same result.
                    if boosting:
                        replay = float(model.predict([features])[0])
                    else:
                        x = (vectorizer.transform([features]) - scaler.mean_) / scaler.scale_
                        replay = float((x @ model.named_steps["ridge"].coef_ + model.named_steps["ridge"].intercept_)[0])
                    require(predicted is not None and math.isclose(replay, predicted, rel_tol=1e-9, abs_tol=1e-8), "Saved prediction differs from model")
                    require(np.allclose(model.predict([features]), [predicted], rtol=1e-9, atol=1e-8), "Reloaded model prediction differs")
                    require(row["latest_input_available_at_local_unverified"] == available_at.isoformat(), "Wrong feature availability")
                    require(math.isclose(float(row["prediction_clipped_diagnostic"]), max(0, predicted), rel_tol=1e-12), "Wrong clipping diagnostic")
                own = actual is not None and predicted is not None
                common = own and all(value is not None for value in baselines[key][timestamp].values()) and len(baselines[key][timestamp]) == 3
                require((row["scored"] == "True") == own, "Wrong scored flag")
                require((row["on_common_comparison_hours"] == "True") == common, "Wrong common-hours flag")
                if own:
                    own_actual.append(actual)
                    own_predicted.append(predicted)
                if common:
                    common_actual.append(actual)
                    common_predicted.append(predicted)
                    for method, value in baselines[key][timestamp].items():
                        common_baselines[method].append(value)
            require(len(common_actual) == group["common_comparison_hours"], "Shared coverage differs")
            compare_scores(measured(common_actual, common_predicted), group[f"{prefix}_common_scores_raw"])
            compare_scores(measured(common_actual, [max(0, value) for value in common_predicted]), group[f"{prefix}_common_scores_clipped_diagnostic"])
            compare_scores(measured(own_actual, own_predicted), group[f"{prefix}_own_available_scores_raw"])
            for method, values in common_baselines.items():
                compare_scores(measured(common_actual, values), group["baseline_common_scores"][method])
            count += 1
    timing = "nominal midnight weather timing" if weather is not None else "midnight inputs"
    model_name = "XGBoost" if boosting else "Ridge"
    print(f"Verified {count} {model_name} models: saved predictions, training-only preprocessing, {timing}, paired errors, source hash and test exclusion.")


if __name__ == "__main__":
    main()
